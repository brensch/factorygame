use bevy::prelude::Color;

/// A palette entry as a Bevy sprite tint.
pub fn col(c: Rgba) -> Color {
    Color::srgba_u8(c[0], c[1], c[2], c[3])
}

/// Item colors, one per class family: raws warm, mids richer, finals bright.
pub fn item_color(t: overflow_core::defs::ItemType) -> Rgba {
    use overflow_core::defs::ItemType::*;
    match t {
        Ore => [0xe0, 0x9a, 0x3c, 0xff],
        Sap => [0x7e, 0xc9, 0x6a, 0xff],
        Crystal => [0x9f, 0xd8, 0xff, 0xff],
        Ingot => [0xe8, 0x62, 0x3c, 0xff],
        Resin => [0x4f, 0xa8, 0x54, 0xff],
        Shard => [0x8f, 0xc8, 0xe8, 0xff],
        Gear => [0xa9, 0x9a, 0xf5, 0xff],
        Circuit => [0x5f, 0xd8, 0xa0, 0xff],
        Lens => [0x6f, 0xb8, 0xff, 0xff],
        Engine => [0xff, 0x8f, 0x4f, 0xff],
        Core => [0xff, 0x5f, 0x8f, 0xff],
        Beacon => [0xff, 0xe8, 0x6f, 0xff],
        Flux => [0x7f, 0xd8, 0xff, 0xff],
        Slag => [0x55, 0x50, 0x48, 0xff],
    }
}
